#!/usr/bin/env node
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));

// Load compiled problems via ts - use dynamic import after build, or read raw
// For sync script, we import the TS via a simple JSON export approach
const problemsPath = join(__dirname, "../src/content/platform-problems/index.ts");

// Generate manifest from a static import - run via tsx
async function main() {
  const { exportProblemsManifest } = await import(
    "../src/content/platform-problems/index.ts"
  );
  const manifest = exportProblemsManifest();
  const outDir = join(__dirname, "../worker/problems");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2));

  // Generate Go registry
  const goEntries = manifest
    .map(
      (p) => `\t"${p.id}": {
\t\tID: "${p.id}",
\t\tMaxHeapAllocs: ${p.maxHeapAllocs},
\t\tTestSuite: ${JSON.stringify(p.testSuite)},
\t},`,
    )
    .join("\n");

  const goFile = `// Code generated by scripts/sync-worker-problems.mjs; DO NOT EDIT.

package problems

var registry = map[string]Problem{
${goEntries}
}

func Get(id string) (Problem, bool) {
\tp, ok := registry[id]
\treturn p, ok
}
`;

  writeFileSync(join(__dirname, "../worker/internal/problems/registry_gen.go"), goFile);
  console.log(`Synced ${manifest.length} problems to worker/problems/manifest.json`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
